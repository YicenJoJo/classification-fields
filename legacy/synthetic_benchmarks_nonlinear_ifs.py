def run_Ltrain_sweep_experiment(
    L_train_values=(1, 2, 3),
    L_total=11,
    n_trials=9,
    d=2,
    K=3,
    scale=0.5,
    lambda_=None,
    x0=None,
    C_radius=1.0,
    nu=3.25,
    sigma_min=0.1,
    sigma_max=1.0,
    hidden_dim_rhg=500,
    hidden_width=64,
    depth=3,
    lr=1e-3,
    epochs=3000,
    print_every=300,
    verbose=True,
    device=None,
):
    """
    Sweep over different training depths L_train and compare extrapolation
    performance of the HRG vs. the average-residual and linear baselines.

    Parameters
    ----------
    L_train_values : tuple of int
        Training depths to compare.
    L_total : int
        Total hierarchy depth (must be > max(L_train_values)).
    n_trials : int
        Number of independent random trials.

    Returns
    -------
    sweep_results : dict
        Keys are L_train values; each value is a dict with:
          - "extrap_levels", "nn_mse_trials", "baseline_mse_trials",
          - "nn_mean", "nn_std", "baseline_mean", "baseline_std"
    """
    if device is None:
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print("Using device:", device)

    if x0 is None:
        x0 = np.zeros(d, dtype=float)
    else:
        x0 = np.asarray(x0, dtype=float).reshape(d)

    if L_total <= max(L_train_values):
        raise ValueError(
            f"L_total ({L_total}) must be strictly greater than "
            f"max(L_train_values) ({max(L_train_values)})."
        )

    sweep_collectors = {}
    for L_tr in L_train_values:
        sweep_collectors[L_tr] = {
            "extrap_levels": np.arange(L_tr + 1, L_total + 1),
            "nn_mse_trials": [],
            "baseline_mse_trials": [],
            "linear_mse_trials": [],
        }

    for trial in range(n_trials):
        seed_C = 1000 + trial
        seed_r = 2000 + trial
        set_seed(seed_C)  # controls torch/numpy/random for this trial

        if verbose:
            print(f"\n{'='*60}")
            print(f"  Trial {trial+1}/{n_trials}  "
                  f"(seed_C={seed_C}, seed_r={seed_r})")
            print(f"{'='*60}")

        C_trial = get_C(d=d, K=K, radius=C_radius, seed=seed_C)

        r_col_trial, r_trial = get_RHG(
            C=C_trial,
            nu=nu,
            sigma_min=sigma_min,
            sigma_max=sigma_max,
            hidden_dim=hidden_dim_rhg,
            seed=seed_r,
        )

        levels_true = build_hierarchy(
            r_trial,
            x0,
            max_level=L_total,
            scale=scale,
            lambda_=lambda_,
            check_contractivity=(lambda_ is not None),
        )

        for L_tr in L_train_values:
            extrap_levels = sweep_collectors[L_tr]["extrap_levels"]
            n_extra = L_total - L_tr

            model = train_hrg_model(
                HRGMLP(d=d, K=K, hidden_width=hidden_width, depth=depth),
                levels_true,
                x0=x0,
                L_train=L_tr,
                n_extra_levels=n_extra,
                K=K,
                scale=scale,
                lr=lr,
                epochs=epochs,
                print_every=print_every,
                device=device,
            )

            levels_hat_nn = build_hierarchy_from_model(
                model, x0, max_level=L_total, scale=scale,
            )

            avg_residuals = estimate_average_residuals(
                levels_true, L_train=L_tr, K=K, scale=scale,
            )

            levels_hat_bl = build_hierarchy_from_average_residuals(
                avg_residuals, x0, max_level=L_total, scale=scale,
            )

            model_lin = train_hrg_model(
                LinearHRG(d=d, K=K), levels_true, x0=x0,
                L_train=L_tr, n_extra_levels=n_extra,
                K=K, scale=scale, lr=lr, epochs=epochs,
                print_every=print_every, device=device,
            )
            levels_hat_lin = build_hierarchy_from_model(
                model_lin, x0, max_level=L_total, scale=scale,
            )

            nn_mse = [np.mean((levels_hat_nn[lev] - levels_true[lev]) ** 2)
                      for lev in extrap_levels]
            bl_mse = [np.mean((levels_hat_bl[lev] - levels_true[lev]) ** 2)
                      for lev in extrap_levels]
            lin_mse = [np.mean((levels_hat_lin[lev] - levels_true[lev]) ** 2)
                       for lev in extrap_levels]

            sweep_collectors[L_tr]["nn_mse_trials"].append(nn_mse)
            sweep_collectors[L_tr]["baseline_mse_trials"].append(bl_mse)
            sweep_collectors[L_tr]["linear_mse_trials"].append(lin_mse)

            if verbose:
                print(f"  L_train={L_tr}:")
                for idx, lev in enumerate(extrap_levels):
                    print(f"    Level {lev}: HRG={nn_mse[idx]:.6e}  "
                          f"BL={bl_mse[idx]:.6e}  "
                          f"Lin={lin_mse[idx]:.6e}")

        if device.type == "cuda":
            torch.cuda.empty_cache()

    sweep_results = {}
    for L_tr in L_train_values:
        nn_arr = np.array(sweep_collectors[L_tr]["nn_mse_trials"], dtype=float)
        bl_arr = np.array(sweep_collectors[L_tr]["baseline_mse_trials"],
                          dtype=float)
        lin_arr = np.array(sweep_collectors[L_tr]["linear_mse_trials"],
                           dtype=float)
        n_ext = len(sweep_collectors[L_tr]["extrap_levels"])
        sweep_results[L_tr] = {
            "extrap_levels": sweep_collectors[L_tr]["extrap_levels"],
            "nn_mse_trials": nn_arr,
            "baseline_mse_trials": bl_arr,
            "linear_mse_trials": lin_arr,
            "nn_mean": nn_arr.mean(axis=0),
            "nn_std": (nn_arr.std(axis=0, ddof=1) if n_trials > 1
                       else np.zeros(n_ext)),
            "baseline_mean": bl_arr.mean(axis=0),
            "baseline_std": (bl_arr.std(axis=0, ddof=1) if n_trials > 1
                             else np.zeros(n_ext)),
            "linear_mean": lin_arr.mean(axis=0),
            "linear_std": (lin_arr.std(axis=0, ddof=1) if n_trials > 1
                           else np.zeros(n_ext)),
        }

    return sweep_results


