def run_synthetic_benchmark(
    benchmark_name,
    benchmark_kwargs=None,
    L_train=2,
    n_extra_levels=3,
    n_trials=9,
    hidden_width=64,
    depth_nn=3,
    lr=1e-3,
    epochs=2000,
    print_every=500,
    device=None,
):
    """
    Run a synthetic fractal benchmark: train HRG + baselines, evaluate
    extrapolation, aggregate over trials.

    For deterministic benchmarks, trials vary through model initialization
    unless noise_std > 0.  For random_affine_ifs and random_nonlinear_ifs,
    the IFS itself is resampled across trials.

    Parameters
    ----------
    benchmark_name : str
        Name of a registered benchmark in BENCHMARK_GENERATORS.
    benchmark_kwargs : dict or None
        Extra kwargs passed to the generator (e.g. depth, noise_std).
    n_trials : int
        Number of independent trials.

    Returns
    -------
    results : dict
    """
    if device is None:
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    gen_fn = BENCHMARK_GENERATORS[benchmark_name]
    bkw = dict(benchmark_kwargs or {})

    L_total_requested = L_train + n_extra_levels
    if "depth" not in bkw:
        bkw["depth"] = L_total_requested

    methods = ["avg_baseline", "constant", "linear", "nn"]
    ordered_collectors = {m: [] for m in methods}
    chamfer_collectors = {m: [] for m in methods}
    dpt_collectors = {m: [] for m in methods}

    for trial in range(n_trials):
        trial_seed = 5000 + trial
        set_seed(trial_seed)  # controls torch/numpy/random for this trial
        trial_bkw = {**bkw}
        if benchmark_name in ("random_affine_ifs", "random_nonlinear_ifs"):
            trial_bkw["seed"] = trial_seed
        elif bkw.get("noise_std", 0) > 0:
            trial_bkw["seed"] = trial_seed

        bench = gen_fn(**trial_bkw)
        levels = bench["levels"]
        K_bench = bench["K"]
        d_bench = bench["d"]
        L_total = min(len(levels) - 1, L_total_requested)
        levels = levels[:L_total + 1]
        x0_bench = levels[0][0]
        extrap_levels = np.arange(L_train + 1, L_total + 1)

        print(f"\n--- {benchmark_name} trial {trial+1}/{n_trials} ---")
        for l, H in enumerate(levels):
            tag = "train" if l <= L_train else "test"
            print(f"  Level {l}: {H.shape[0]} nodes  ({tag})")

        # --- Average residual baseline ---
        avg_res = estimate_average_residuals(
            levels, L_train=L_train, K=K_bench, scale=1.0,
        )
        levels_hat_avg = build_hierarchy_from_average_residuals(
            avg_res, x0_bench, max_level=L_total, scale=1.0,
        )

        # --- Learnable constant baseline ---
        model_const = train_hrg_model(
            ConstantHRG(d=d_bench, K=K_bench), levels, x0=x0_bench,
            L_train=L_train, n_extra_levels=n_extra_levels,
            K=K_bench, scale=1.0, lr=lr, epochs=epochs,
            print_every=print_every, device=device,
        )
        levels_hat_const = build_hierarchy_from_model(
            model_const, x0_bench, max_level=L_total, scale=1.0,
        )

        # --- Linear baseline ---
        model_lin = train_hrg_model(
            LinearHRG(d=d_bench, K=K_bench), levels, x0=x0_bench,
            L_train=L_train, n_extra_levels=n_extra_levels,
            K=K_bench, scale=1.0, lr=lr, epochs=epochs,
            print_every=print_every, device=device,
        )
        levels_hat_lin = build_hierarchy_from_model(
            model_lin, x0_bench, max_level=L_total, scale=1.0,
        )

        # --- HRG ---
        # Uses the same optimizer config (train_hrg_model) as baselines for
        # a fair comparison across methods.
        model_nn = train_hrg_model(
            HRGMLP(d=d_bench, K=K_bench, hidden_width=hidden_width, depth=depth_nn),
            levels, x0=x0_bench,
            L_train=L_train, n_extra_levels=n_extra_levels,
            K=K_bench, scale=1.0, lr=lr, epochs=epochs,
            print_every=print_every, device=device,
        )
        levels_hat_nn = build_hierarchy_from_model(
            model_nn, x0_bench, max_level=L_total, scale=1.0,
        )

        hats = {
            "avg_baseline": levels_hat_avg,
            "constant": levels_hat_const,
            "linear": levels_hat_lin,
            "nn": levels_hat_nn,
        }

        for m in methods:
            ord_mse = [np.mean((hats[m][lv] - levels[lv]) ** 2)
                       for lv in extrap_levels]
            cham = [chamfer_distance(hats[m][lv], levels[lv])
                    for lv in extrap_levels]
            dpt = [dpt_distortion(hats[m], levels, K_bench, upto_level=lv,
                                  normalize="diameter")
                   for lv in extrap_levels]
            ordered_collectors[m].append(ord_mse)
            chamfer_collectors[m].append(cham)
            dpt_collectors[m].append(dpt)

        if device.type == "cuda":
            torch.cuda.empty_cache()

    results = {
        "benchmark": benchmark_name,
        "K": bench["K"],
        "d": bench["d"],
        "extrap_levels": extrap_levels,
        "L_train": L_train,
        "n_trials": n_trials,
    }
    n_el = len(extrap_levels)
    zero_std = np.zeros(n_el)
    for m in methods:
        arr_o = np.array(ordered_collectors[m], dtype=float)
        arr_c = np.array(chamfer_collectors[m], dtype=float)
        arr_d = np.array(dpt_collectors[m], dtype=float)
        results[m] = {
            "ordered_mse_trials": arr_o,
            "chamfer_trials": arr_c,
            "dpt_trials": arr_d,
            "ordered_mean": arr_o.mean(axis=0),
            "ordered_std": arr_o.std(axis=0, ddof=1) if n_trials > 1 else zero_std,
            "chamfer_mean": arr_c.mean(axis=0),
            "chamfer_std": arr_c.std(axis=0, ddof=1) if n_trials > 1 else zero_std,
            "dpt_mean": arr_d.mean(axis=0),
            "dpt_std": arr_d.std(axis=0, ddof=1) if n_trials > 1 else zero_std,
        }

    return results


