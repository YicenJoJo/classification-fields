    fig, axes = plt.subplots(1, n_vis, figsize=(5 * n_vis, 5), squeeze=False)
    axes = axes[0]
    for vi, (tag, lvs) in enumerate(vis_variants):
        ax = axes[vi]
        H0 = lvs[0]
        ax.scatter(H0[:, 0], H0[:, 1], color="black", s=90, zorder=5)

        for l in range(1, len(lvs)):
            parents = lvs[l - 1]
            children = lvs[l]
            for j, child in enumerate(children):
                parent = parents[j // _K]
                slot = j % _K
                ax.plot(
                    [parent[0], child[0]], [parent[1], child[1]],
                    color=slot_colors[slot], alpha=0.6, lw=1.5, zorder=1,
                )
                ax.scatter(
                    child[0], child[1],
                    color=slot_colors[slot], s=60, zorder=3,
                    edgecolors="black", linewidths=0.4,
                )

        ax.set_title(tag, fontsize=13, fontweight="bold")
        ax.set_xlabel("$x_1$")
        ax.set_ylabel("$x_2$")
        ax.set_aspect("equal", adjustable="datalim")
        ax.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig(f"{OUTPUT_DIR}/perm_sanity_check_qualitative.png", dpi=500, bbox_inches="tight")
    plt.savefig(f"{OUTPUT_DIR}/perm_sanity_check_qualitative.pdf", bbox_inches="tight")
    print(f"Saved: {OUTPUT_DIR}/perm_sanity_check_qualitative.png / .pdf")
    plt.show()

    # ==================================================================
    # Summary table
    # ==================================================================
    print("\n" + "=" * 95)
    print("PERMUTATION SANITY CHECK — SUMMARY")
    print("=" * 95)
    print(f"{'Setting':<28} | {'Method':<24} | {'Deepest-Level MSE':>18} "
          f"| {'Avg MSE (all extrap)':>20}")
    print("-" * 95)
    for setting, label in settings_labels.items():
        res = perm_results[setting]
        for method, key_mean in [("HRG", "nn_mean"),
                                 ("Avg Residual", "baseline_mean"),
                                 ("Linear Res. Gen.", "linear_mean")]:
            deepest = res[key_mean][-1]
            avg_all = res[key_mean].mean()
            print(f"  {label:<26} | {method:<24} | {deepest:>18.6e} "
                  f"| {avg_all:>20.6e}")
    print("=" * 95)

    return perm_results


