def sigmoid(z):
    return 1.0 / (1.0 + np.exp(-z))

"""Sample C on there $\mathbf{S}^{d-1}$ according to the Haar measure."""

def get_C(d, K, radius=1.0, seed=None):
    """
    Returns C of shape (d, K), whose columns are i.i.d. Haar-uniform
    on the sphere of radius `radius` in R^d.
    """
    rng = np.random.default_rng(seed)
    G = rng.standard_normal((d, K))              # columns ~ N(0, I_d)
    G /= np.linalg.norm(G, axis=0, keepdims=True)
    return radius * G

