def generate_cantor_dust(depth=5, x0=None, noise_std=0.0, seed=None):
    """
    2D product Cantor set via the IFS:
        f_k(x) = x/3 + b_k,  k = 0, 1, 2, 3
    where b_k are the four corner offsets: (0,0), (2/3,0), (0,2/3), (2/3,2/3).

    The residual r(x)_k = -2x/3 + b_k  is affine in x.
    """
    I2 = np.eye(2)
    offsets = [
        np.array([0.0, 0.0]),
        np.array([2.0 / 3, 0.0]),
        np.array([0.0, 2.0 / 3]),
        np.array([2.0 / 3, 2.0 / 3]),
    ]

    maps = [make_affine_map(I2 / 3, b) for b in offsets]

    if x0 is None:
        x0 = np.array([0.5, 0.5])

    levels = build_ifs_hierarchy(maps, x0, depth, noise_std, seed)

    return make_benchmark_dict(
        name="cantor_dust",
        levels=levels,
        K=4,
        maps=maps,
        metadata={"offsets": offsets, "contraction": 1.0 / 3},
    )


