def make_affine_map(A, b):
    """Return a callable f(x) = A @ x + b."""
    A = np.asarray(A, dtype=float)
    b = np.asarray(b, dtype=float)
    def f(x):
        return A @ x + b
    return f


def make_smooth_warped_map(
    A,
    b,
    amp=0.02,
    freq1=(1.0, 0.7),
    freq2=(-0.6, 1.2),
    phase=0.0,
    quad=0.0,
):
    """
    Return a smooth nonlinear IFS map

        f(x) = A x + b
               + amp * [sin(<w1,x> + phase), cos(<w2,x> - 0.37 phase)]
               + quad * [x1*x2, x1^2 - x2^2].

    The sinusoidal and quadratic terms make the residual rule
        r_k(x) = f_k(x) - x
    genuinely nonlinear, so a per-slot affine residual generator cannot contain
    the ground-truth rule.  The default amplitudes are deliberately small: the
    maps remain smooth contractions on the bounded regions visited by these
    benchmarks, while the affine baseline still has visible approximation error.
    """
    A = np.asarray(A, dtype=float)
    b = np.asarray(b, dtype=float)
    w1 = np.asarray(freq1, dtype=float)
    w2 = np.asarray(freq2, dtype=float)

    def f(x):
        x = np.asarray(x, dtype=float).reshape(-1)
        nonlin = np.array([
            np.sin(float(w1 @ x) + phase),
            np.cos(float(w2 @ x) - 0.37 * phase),
        ])
        q = np.array([x[0] * x[1], x[0] * x[0] - x[1] * x[1]])
        return A @ x + b + amp * nonlin + quad * q

    return f


def _rot2(theta):
    """2D rotation matrix."""
    c, s = np.cos(theta), np.sin(theta)
    return np.array([[c, -s], [s, c]])


def build_ifs_hierarchy(maps, x0, depth, noise_std=0.0, seed=None):
    """
    Construct a hierarchy by iterating an IFS from a root point.

    At each level, every parent generates K children via the K maps.
    Children are stored parent-by-parent:
        levels[l+1][j*K + k]  is the k-th child of parent j at level l.

    Parameters
    ----------
    maps : list of K callables  f_k : R^d -> R^d
    x0 : np.ndarray, shape (d,)
    depth : int
    noise_std : float
        Isotropic Gaussian noise added to each child.
    seed : int or None

    Returns
    -------
    levels : list of np.ndarray
        levels[l] has shape (K^l, d).
    """
    rng = np.random.default_rng(seed) if noise_std > 0 else None
    K = len(maps)
    x0 = np.asarray(x0, dtype=float).ravel()
    d = x0.shape[0]

    levels = [x0.reshape(1, d)]

    for l in range(1, depth + 1):
        parents = levels[-1]
        n_parents = parents.shape[0]
        children = np.empty((n_parents * K, d), dtype=float)

        for p_idx in range(n_parents):
            for k in range(K):
                child = maps[k](parents[p_idx])
                if rng is not None and noise_std > 0:
                    child = child + rng.normal(0, noise_std, size=d)
                children[p_idx * K + k] = child

        levels.append(children)

    return levels


def make_benchmark_dict(name, levels, K, maps, metadata=None):
    """Package a benchmark into the unified dict format."""
    depth = len(levels) - 1
    d = levels[0].shape[1]

    parent_indices = []
    child_order = []
    for l in range(depth):
        n_children = levels[l + 1].shape[0]
        parent_indices.append(np.arange(n_children) // K)
        child_order.append(np.arange(n_children) % K)

    return {
        "name": name,
        "levels": levels,
        "K": K,
        "d": d,
        "depth": depth,
        "maps": maps,
        "parent_indices": parent_indices,
        "child_order": child_order,
        "metadata": metadata or {},
    }


