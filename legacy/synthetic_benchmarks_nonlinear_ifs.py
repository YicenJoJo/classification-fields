def chamfer_distance(pred, true, squared=True):
    """Symmetric Chamfer distance between two point sets.

    CD = mean_{x in pred} min_{y in true} ||x-y||^2
       + mean_{y in true} min_{x in pred} ||x-y||^2

    Uses squared Euclidean by default.  O(N*M) distance matrix.
    """
    diff = pred[:, None, :] - true[None, :, :]          # (N, M, d)
    dist2 = np.sum(diff ** 2, axis=2)                    # (N, M)
    if not squared:
        dist2 = np.sqrt(dist2 + 1e-30)
    fwd = np.mean(np.min(dist2, axis=1))                 # pred → true
    bwd = np.mean(np.min(dist2, axis=0))                 # true → pred
    return float(fwd + bwd)


def flatten_levels_upto(levels, upto_level, K):
    """Flatten hierarchy levels 0..upto_level into arrays.

    Returns
    -------
    points : (N, d)
    parent_global : (N,)   -1 for root
    level_ids : (N,)
    """
    points, parent_global, level_ids = [], [], []
    offset = 0
    offsets = []
    for l in range(upto_level + 1):
        offsets.append(offset)
        n_l = levels[l].shape[0]
        points.append(levels[l])
        level_ids.append(np.full(n_l, l, dtype=int))
        if l == 0:
            parent_global.append(np.array([-1], dtype=int))
        else:
            parent_local = np.arange(n_l, dtype=int) // K
            parent_global.append(offsets[l - 1] + parent_local)
        offset += n_l

    return (
        np.vstack(points),
        np.concatenate(parent_global),
        np.concatenate(level_ids),
    )


def compute_dpt_matrix(levels, K, upto_level):
    """Compute pairwise tree-shortest-path distance matrix using Euclidean
    edge weights on the hierarchy up to upto_level.

    d(u,v) = dist_root[u] + dist_root[v] - 2*dist_root[lca(u,v)]

    Returns D of shape (N, N).
    """
    points, parent_global, level_ids = flatten_levels_upto(
        levels, upto_level, K,
    )
    N = len(points)

    edge_len = np.zeros(N)
    for i in range(N):
        p = parent_global[i]
        if p >= 0:
            edge_len[i] = np.linalg.norm(points[i] - points[p])

    dist_root = np.zeros(N)
    for i in range(N):
        p = parent_global[i]
        if p >= 0:
            dist_root[i] = dist_root[p] + edge_len[i]

    ancestors = np.full((N, int(upto_level) + 1), -1, dtype=int)
    cum_dist = np.zeros((N, int(upto_level) + 1))
    for i in range(N):
        cur = i
        lv = level_ids[i]
        for step in range(lv + 1):
            ancestors[i, step] = cur
            cum_dist[i, step] = dist_root[i] - dist_root[cur]
            if parent_global[cur] >= 0:
                cur = parent_global[cur]

    D = np.zeros((N, N))
    for i in range(N):
        for j in range(i + 1, N):
            anc_i = set()
            cur = i
            while cur >= 0:
                anc_i.add(cur)
                cur = parent_global[cur]
            lca = j
            while lca not in anc_i:
                lca = parent_global[lca]
            d_ij = (dist_root[i] - dist_root[lca]) + \
                   (dist_root[j] - dist_root[lca])
            D[i, j] = d_ij
            D[j, i] = d_ij

    return D


def dpt_distortion(pred_levels, true_levels, K, upto_level,
                   normalize="diameter"):
    """Structure-aware d_pt-distortion between predicted and true hierarchies.

    Compares pairwise tree-shortest-path distances (Euclidean edge weights).
    Returns mean absolute difference of upper-triangular entries,
    optionally normalized.
    """
    D_pred = compute_dpt_matrix(pred_levels, K, upto_level)
    D_true = compute_dpt_matrix(true_levels, K, upto_level)
    N = D_pred.shape[0]

    iu = np.triu_indices(N, k=1)
    diff = np.abs(D_pred[iu] - D_true[iu])
    raw = np.mean(diff)

    if normalize == "diameter":
        diam = np.max(D_true[iu]) + 1e-30
        return float(raw / diam)
    elif normalize == "mean":
        mu = np.mean(D_true[iu]) + 1e-30
        return float(raw / mu)
    else:
        return float(raw)


