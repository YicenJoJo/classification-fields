def _plot_metric_comparison(all_bench_results, metric_key, ylabel, fname_stem,
                            method_cfg):
    """Generic helper: one panel per benchmark, semilogy of a given metric."""
    bench_names = list(all_bench_results.keys())
    n_bench = len(bench_names)

    fig, axes = plt.subplots(1, n_bench, figsize=(5.5 * n_bench, 5),
                             sharey=True, squeeze=False)
    axes = axes[0]

    for i, bname in enumerate(bench_names):
        ax = axes[i]
        res = all_bench_results[bname]
        elvs = res["extrap_levels"]

        for m, (label, color, marker, ls) in method_cfg.items():
            trials = res[m][f"{metric_key}_trials"]
            log_vals = np.log10(trials + 1e-30)
            log_mean = log_vals.mean(axis=0)
            log_std = (log_vals.std(axis=0, ddof=1) if res["n_trials"] > 1
                       else np.zeros(len(elvs)))

            geo_mean = 10 ** log_mean
            geo_lo = 10 ** (log_mean - log_std)
            geo_hi = 10 ** (log_mean + log_std)

            ax.semilogy(elvs, geo_mean, marker=marker, linestyle=ls,
                        color=color, lw=2, ms=6, label=label)
            ax.fill_between(elvs, geo_lo, geo_hi, color=color, alpha=0.12)

        ax.set_xlabel("Level", fontsize=11)
        if i == 0:
            ax.set_ylabel(ylabel, fontsize=11)
        ax.set_title(bname.replace("_", " ").title(), fontsize=12,
                     fontweight="bold")
        ax.set_xticks(elvs)
        if i == n_bench - 1:
            ax.legend(fontsize=11, loc="upper right")
        ax.grid(True, alpha=0.3, which="both")

    plt.tight_layout()
    plt.savefig(f"{OUTPUT_DIR}/{fname_stem}.png", dpi=500, bbox_inches="tight")
    plt.savefig(f"{OUTPUT_DIR}/{fname_stem}.pdf", bbox_inches="tight")
    print(f"Saved: {OUTPUT_DIR}/{fname_stem}.png / .pdf")
    plt.show()


