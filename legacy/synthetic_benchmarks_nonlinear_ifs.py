# Benchmark 1: Sierpinski Triangle  (K=3, d=2)
# ============================================================

def generate_sierpinski(depth=7, x0=None, noise_std=0.0, seed=None):
    """
    Sierpinski triangle via the IFS:
        f_k(x) = x/2 + v_k/2,  k = 0, 1, 2
    where v_0, v_1, v_2 are the vertices of an equilateral triangle.

    The residual r(x)_k = f_k(x) - x = v_k/2 - x/2  is affine in x.
    """
    v0 = np.array([0.0, 0.0])
    v1 = np.array([1.0, 0.0])
    v2 = np.array([0.5, np.sqrt(3) / 2])
    verts = [v0, v1, v2]

    I2 = np.eye(2)
    maps = [make_affine_map(I2 / 2, v / 2) for v in verts]

    if x0 is None:
        x0 = (v0 + v1 + v2) / 3

    levels = build_ifs_hierarchy(maps, x0, depth, noise_std, seed)

    return make_benchmark_dict(
        name="sierpinski",
        levels=levels,
        K=3,
        maps=maps,
        metadata={"vertices": verts, "contraction": 0.5},
    )


