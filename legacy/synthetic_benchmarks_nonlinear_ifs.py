def generate_random_nonlinear_ifs(
    K=3,
    d=2,
    depth=6,
    x0=None,
    contraction_range=(0.20, 0.38),
    noise_std=0.0,
    seed=None,
):
    """
    Random smooth nonlinear IFS (K=3 by default).

    Each map is a random affine contraction plus a small sinusoidal/quadratic
    warp.  The seed controls the random IFS itself, so different trials evaluate
    different nonlinear recursive laws.
    """
    if d != 2:
        raise ValueError("generate_random_nonlinear_ifs currently supports d=2 only.")

    rng = np.random.default_rng(seed)
    maps = []
    metadata = []

    for k in range(K):
        c = rng.uniform(*contraction_range)
        theta = rng.uniform(0, 2 * np.pi)
        A = c * _rot2(theta)
        b = rng.uniform(-0.45, 0.45, size=2)

        w1 = rng.normal(size=2)
        w1 = w1 / (np.linalg.norm(w1) + 1e-12) * rng.uniform(2.5, 3.5)
        w2 = rng.normal(size=2)
        w2 = w2 / (np.linalg.norm(w2) + 1e-12) * rng.uniform(2.5, 3.5)
        phase = rng.uniform(0, 2 * np.pi)
        amp = rng.uniform(0.055, 0.085)
        quad = 0.0

        maps.append(make_smooth_warped_map(A, b, amp, w1, w2, phase, quad))
        metadata.append({
            "A": A, "b": b, "freq1": w1, "freq2": w2,
            "phase": phase, "amp": amp, "quad": quad,
        })

    if x0 is None:
        x0 = np.zeros(2)

    levels = build_ifs_hierarchy(maps, x0, depth, noise_std, seed)
    return make_benchmark_dict(
        name="random_nonlinear_ifs",
        levels=levels,
        K=K,
        maps=maps,
        metadata={"seed": seed, "maps": metadata, "nonlinear": True},
    )


