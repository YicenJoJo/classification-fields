# ============================================================
# 1. Build supervised training data from hierarchy levels
# ============================================================

def hierarchy_to_training_data(levels, K=3, scale=1.0):
    """
    Convert hierarchy levels [H_0, ..., H_L] into supervised data.

    Parameters
    ----------
    levels : list of np.ndarray
        levels[l] has shape (n_l, d), where n_l = K^l in the full-tree case.
    K : int
        Number of children per parent.
    scale : float, default=1.0
        Scaling factor s. A parent at level l generates children via
            x + s^l r(x)_k.

    Returns
    -------
    X : torch.Tensor, shape (N, d)
        Parent nodes.
    Y : torch.Tensor, shape (N, K, d)
        Corresponding children of each parent.
    S : torch.Tensor, shape (N, 1, 1)
        Per-sample scaling factors s^l, where l is the level of the parent.
    """
    if not (0 < scale <= 1):
        raise ValueError(f"scale must satisfy 0 < scale <= 1, but got {scale}.")

    X_list = []
    Y_list = []
    S_list = []

    for l in range(len(levels) - 1):
        parents = levels[l]        # shape (n_l, d)
        children = levels[l + 1]   # shape (n_{l+1}, d)

        n_parents, d = parents.shape

        if children.shape[0] != n_parents * K:
            raise ValueError(
                f"Level {l+1} should have {n_parents*K} nodes, "
                f"but got {children.shape[0]}."
            )

        # By construction in build_hierarchy, children are ordered parent-by-parent
        children_grouped = children.reshape(n_parents, K, d)

        X_list.append(parents)
        Y_list.append(children_grouped)

        level_scales = np.full((n_parents, 1, 1), scale ** (l + 1), dtype=np.float32)
        S_list.append(level_scales)

    X = np.vstack(X_list)                  # (N, d)
    Y = np.vstack(Y_list)                  # (N, K, d)
    S = np.vstack(S_list)                  # (N, 1, 1)

    return (
        torch.tensor(X, dtype=torch.float32),
        torch.tensor(Y, dtype=torch.float32),
        torch.tensor(S, dtype=torch.float32),
    )


# ============================================================
# 2. MLP for residual generator \hat r : R^d -> R^{dK}
# ============================================================

class HRGMLP(nn.Module):
    def __init__(self, d=2, K=3, hidden_width=64, depth=3):
        super().__init__()
        layers = []

        in_dim = d
        for _ in range(depth):
            layers.append(nn.Linear(in_dim, hidden_width))
            layers.append(nn.ReLU())
            in_dim = hidden_width

        layers.append(nn.Linear(in_dim, d * K))
        self.net = nn.Sequential(*layers)

        self.d = d
        self.K = K

    def forward(self, x):
        """
        x: shape (batch, d)
        returns: shape (batch, K, d)
        """
        out = self.net(x)                  # (batch, d*K)
        return out.view(-1, self.K, self.d)


# ============================================================
# 2b. Learnable constant residual model: r_hat(x)_k = c_k
# ============================================================

class ConstantHRG(nn.Module):
    """
    Location-independent learnable residual generator.
    The K residual vectors c_1, ..., c_K are free parameters that do not
    depend on the input x.
    """
    def __init__(self, d=2, K=3):
        super().__init__()
        self.d = d
        self.K = K
        self.residuals = nn.Parameter(torch.randn(K, d) * 0.1)

    def forward(self, x):
        return self.residuals.unsqueeze(0).expand(x.shape[0], -1, -1)


# ============================================================
# 2c. Linear (affine) residual model: r_hat(x)_k = A_k x + b_k
# ============================================================

class LinearHRG(nn.Module):
    """
    Affine residual generator.  Maps x -> K*d outputs via a single linear
    layer (no hidden layers, no activation), then reshapes to (K, d).
    """
    def __init__(self, d=2, K=3):
        super().__init__()
        self.d = d
        self.K = K
        self.linear = nn.Linear(d, d * K)

    def forward(self, x):
        return self.linear(x).view(-1, self.K, self.d)


# ============================================================
# 2d. Generic training loop for any model with
#     forward(x) -> (batch, K, d) interface
# ============================================================

def train_hrg_model(
    model,
    levels,
    x0=None,
    L_train=None,
    n_extra_levels=1,
    K=3,
    scale=1.0,
    lr=1e-3,
    epochs=2000,
    print_every=200,
    device=None,
):
    """
    Train an arbitrary residual-generator model using hierarchy_loss.
    Accepts any nn.Module with forward(x) -> (batch, K, d).
    """
    if L_train is None:
        L_train = len(levels) - 1
    if device is None:
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    target_level = L_train + n_extra_levels
    can_test = (
        x0 is not None and n_extra_levels >= 1
        and target_level < len(levels)
    )

    train_levels = levels[:L_train + 1]
    X, Y, S = hierarchy_to_training_data(train_levels, K=K, scale=scale)
    X, Y, S = X.to(device), Y.to(device), S.to(device)

    model = model.to(device)
    optimizer = optim.Adam(model.parameters(), lr=lr)

    for epoch in range(1, epochs + 1):
        model.train()
        optimizer.zero_grad()
        loss = hierarchy_loss(model, X, Y, S)
        loss.backward()
        optimizer.step()

        is_log_epoch = (epoch % print_every == 0 or epoch == 1 or epoch == epochs)
        if is_log_epoch:
            with torch.no_grad():
                model.eval()
                pred_train = X.unsqueeze(1) + S * model(X)
                train_mse = ((pred_train - Y) ** 2).mean().item()
                test_str = ""
                if can_test:
                    lh = build_hierarchy_from_model(
                        model, x0, max_level=target_level, scale=scale,
                    )
                    test_mse = np.mean((lh[target_level] - levels[target_level]) ** 2)
                    test_str = f" | Test MSE@L{target_level} = {test_mse:.8f}"
                print(f"Epoch {epoch:5d} | Loss = {loss.item():.8f} | "
                      f"Train MSE = {train_mse:.8f}{test_str}")

    model.eval()
    return model


# ============================================================
# 3. Loss corresponding to
#    sum || x + s^l \hat r(x)_k - chld(x)_k ||^2
# ============================================================

def hierarchy_loss(model, X, Y, S):
    """
    X: (N, d)        parent nodes
    Y: (N, K, d)     observed children
    S: (N, 1, 1)     scaling factors s^l attached to each parent

    returns scalar loss
    """
    pred_residuals = model(X)                     # (N, K, d)
    pred_children = X.unsqueeze(1) + S * pred_residuals
    return ((pred_children - Y) ** 2).sum()


