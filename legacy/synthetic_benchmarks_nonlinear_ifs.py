# --------------------------------------------------
# Baseline: constant average residual generator
# (module-level so the fractal benchmark suite can use them)
# --------------------------------------------------

def estimate_average_residuals(levels, L_train, K=3, scale=1.0):
    """
    Estimate a constant residual generator by averaging the observed
    normalized residuals over the training hierarchy levels.

    If children are generated by
        child = parent + s^l r(parent)_k,
    then the observed residual is estimated as
        r(parent)_k = (child - parent) / s^l.

    We average these residuals over all observed parent-child edges in
    levels 0, ..., L_train-1, separately for each child index k.
    """
    if L_train < 1:
        raise ValueError('L_train must be at least 1.')

    residual_sums = None
    count = 0

    for l in range(1, L_train + 1):
        parents = levels[l - 1]
        children = levels[l]
        n_parents, d = parents.shape
        children_grouped = children.reshape(n_parents, K, d)

        level_residuals = (children_grouped - parents[:, None, :]) / (scale ** l)

        if residual_sums is None:
            residual_sums = level_residuals.sum(axis=0)
        else:
            residual_sums += level_residuals.sum(axis=0)
        count += n_parents

    avg_residuals = residual_sums / count
    return avg_residuals


def build_hierarchy_from_average_residuals(avg_residuals, x0, max_level=2, scale=1.0):
    """
    Roll out a hierarchy using a constant average residual generator.
    At each parent x and level l, generate children by
        x + s^l * avg_residuals[k].
    """
    if not (0 < scale <= 1):
        raise ValueError(f'scale must satisfy 0 < scale <= 1, but got {scale}.')

    x0 = np.asarray(x0, dtype=float).reshape(-1)
    avg_residuals = np.asarray(avg_residuals, dtype=float)

    levels_avg = [x0[None, :]]

    for l in range(1, max_level + 1):
        parents = levels_avg[-1]
        children_list = []
        level_scale = scale ** l

        for x in parents:
            children = x[None, :] + level_scale * avg_residuals
            children_list.append(children)

        levels_avg.append(np.vstack(children_list))

    return levels_avg


# ============================================================
# Helper: random per-parent child permutation
# ============================================================

def permute_hierarchy_levels(levels, K, seed=None):
    """
    Apply independent random per-parent child permutations at every level.
    Deeper subtrees are rearranged to keep the tree structure consistent.

    Parameters
    ----------
    levels : list of np.ndarray
        Hierarchy [H_0, ..., H_L], where H_l has shape (K^l, d).
    K : int
        Branching factor.
    seed : int or None
        Random seed for reproducibility.

    Returns
    -------
    levels_perm : list of np.ndarray
        Permuted hierarchy with the same node coordinates but shuffled
        child ordering within each parent's block.
    """
    rng = np.random.default_rng(seed)
    levels_perm = [lev.copy() for lev in levels]

    for l in range(1, len(levels_perm)):
        n_parents = levels_perm[l - 1].shape[0]

        perms = np.argsort(rng.random((n_parents, K)), axis=1)
        base = np.arange(n_parents)[:, None] * K
        new_order = (base + perms).ravel()

        levels_perm[l] = levels_perm[l][new_order]

        for deeper in range(l + 1, len(levels_perm)):
            block_size = K ** (deeper - l)
            offsets = np.arange(block_size)
            new_order_deep = (
                new_order[:, None] * block_size + offsets[None, :]
            ).ravel()
            levels_perm[deeper] = levels_perm[deeper][new_order_deep]

    return levels_perm


