@torch.no_grad()
def build_hierarchy_from_model(model, x0, max_level=2, scale=1.0):
    """
    Construct [H_0, ..., H_max_level] from the learned model using
        H_l = { x + s^l \hat r(x)_k }.
    Runs entirely on the model's device and copies to CPU once at the end.
    """
    if not (0 < scale <= 1):
        raise ValueError(f"scale must satisfy 0 < scale <= 1, but got {scale}.")

    device = next(model.parameters()).device
    x0_t = torch.tensor(
        np.asarray(x0, dtype=np.float32).reshape(1, -1), device=device,
    )

    levels_t = [x0_t]

    for l in range(1, max_level + 1):
        parents = levels_t[-1]                                     # (n_parents, d)
        level_scale = scale ** l
        residuals = model(parents)                                 # (n_parents, K, d)
        children = parents.unsqueeze(1) + level_scale * residuals  # (n_parents, K, d)
        children = children.reshape(-1, parents.shape[1])          # (n_parents*K, d)
        levels_t.append(children)

    return [lev.cpu().numpy() for lev in levels_t]

