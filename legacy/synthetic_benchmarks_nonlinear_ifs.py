# Helper: angle-based canonical child ordering (d=2)
# ============================================================

def canonicalize_hierarchy_levels(levels, K):
    """
    Reorder each parent's children by the atan2 angle of the displacement
    vector (child - parent), with Euclidean distance as a tie-breaker.
    Works for d=2.  Deeper subtrees are rearranged for tree consistency.

    Parameters
    ----------
    levels : list of np.ndarray
        Hierarchy [H_0, ..., H_L].
    K : int
        Branching factor.

    Returns
    -------
    levels_canon : list of np.ndarray
        Canonicalized hierarchy.
    """
    levels_canon = [lev.copy() for lev in levels]

    for l in range(1, len(levels_canon)):
        n_parents = levels_canon[l - 1].shape[0]

        children_grouped = levels_canon[l].reshape(n_parents, K, -1)
        parents_expanded = levels_canon[l - 1][:, None, :]
        disp = children_grouped - parents_expanded

        angles = np.arctan2(disp[:, :, 1], disp[:, :, 0])
        dists = np.linalg.norm(disp, axis=2)

        new_order = np.empty(n_parents * K, dtype=int)
        base = np.arange(n_parents)[:, None] * K
        for p in range(n_parents):
            sort_idx = np.lexsort((dists[p], angles[p]))
            new_order[p * K : (p + 1) * K] = p * K + sort_idx

        levels_canon[l] = levels_canon[l][new_order]

        for deeper in range(l + 1, len(levels_canon)):
            block_size = K ** (deeper - l)
            offsets = np.arange(block_size)
            new_order_deep = (
                new_order[:, None] * block_size + offsets[None, :]
            ).ravel()
            levels_canon[deeper] = levels_canon[deeper][new_order_deep]

    return levels_canon


