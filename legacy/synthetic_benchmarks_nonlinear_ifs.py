"""---

## Helper Function(s)

This helper function takes a (contractive) residual map $r:\mathbb{R}^d\to \mathbb{R}^{d\times K}$; here $d=2$, and iteratively defines the clusters as follows (quoting the paper):

Given an initial condition $x_0\in \mathbb{R}^d$ and a *scaling factor* $0<s \le 1$, the cluster centres are defined iteratively as follows:
$$
\mathcal{H}
:=
\cup_{l=0}^{\infty}\,
\mathcal{H}_l
$$
where the clusters at any *level* $l\in \mathbb{N}_+$ are defined recursively as
$$
\mathcal{H}_0 := \{x_0\}
$$
and for any subsequent level $l\in \mathbb{N}_+$ we write
$$
\mathcal{H}_l := \Big\{
    x+s^l\,r_f(x)_k:\, k=1,\dots,K;\, x\in \mathcal{H}_{l-1}
\Big\}
.
$$

In other words, the $l^{\text{th}}$ level of the hierarchy consists of a fixed perturbation rule, whereby $K$ residuals are added to the previous parent node to construct its $K$ children; this is performed once for each parent at the $(l-1)^{\text{st}}$ level to obtain the hierarchy.
"""


def build_hierarchy(
    r: Callable[[np.ndarray], np.ndarray],
    x0: np.ndarray,
    max_level: int = 2,
    scale: float = 0.5,
    lambda_: Optional[float] = None,
    check_contractivity: bool = False,
    tol: float = 1e-12,
) -> List[np.ndarray]:
    """
    Construct the hierarchy [H_0, H_1, ..., H_max_level] generated by a
    hierarchical residual generator r, starting from x0, with scaling factor s.

    Parameters
    ----------
    r : callable
        Residual map. Given x of shape (d,), returns an array of residuals
        of shape (n_children, d), where the kth row is r(x)_k.
    x0 : np.ndarray
        Initial point in R^d, shape (d,).
    max_level : int, default=2
        Maximum hierarchy depth to construct.
    scale : float, default=0.5
        Scaling factor s. At level l, children are generated via
            x + s^l r(x)_k.
        Typically one assumes 0 < s < 1.
    lambda_ : float or None, default=None
        Claimed contraction coefficient. Only used if check_contractivity=True.
    check_contractivity : bool, default=False
        If True, checks numerically at every generated node that
            max_k ||r(x)_k||_2 <= lambda_ + tol.
    tol : float, default=1e-12
        Numerical tolerance for the contractivity check.

    Returns
    -------
    levels : list of np.ndarray
        levels[l] is the array representing H_l.
        It has shape (n_l, d), where n_l is the number of nodes at level l.

    Notes
    -----
    This implements
        H_0 = {x0},
        H_l = {x + s^l r(x)_k : k=1,...,K(x), x in H_{l-1}},
    where K(x) is inferred from the number of rows returned by r(x).

    If your r(x) returns shape (d, K) instead of (K, d), replace the line

        residuals = np.asarray(r(x), dtype=float)

    by

        residuals = np.asarray(r(x), dtype=float).T
    """
    if not (0 < scale <= 1):
        raise ValueError(f"scale must satisfy 0 < scale <= 1, but got {scale}.")

    x0 = np.asarray(x0, dtype=float).reshape(-1)
    d = x0.shape[0]

    levels: List[np.ndarray] = [x0[None, :]]

    for level in range(1, max_level + 1):
        parents = levels[-1]
        children_list = []
        level_scale = scale ** level

        for x in parents:
            residuals = np.asarray(r(x), dtype=float)

            if residuals.ndim != 2:
                raise ValueError(
                    f"r(x) must return a 2D array of shape (n_children, d), "
                    f"but got shape {residuals.shape}."
                )

            if residuals.shape[1] != d:
                raise ValueError(
                    f"r(x) must return residuals in R^{d}, "
                    f"but got shape {residuals.shape}."
                )

            if check_contractivity:
                if lambda_ is None:
                    raise ValueError(
                        "If check_contractivity=True, you must provide lambda_."
                    )
                max_norm = np.max(np.linalg.norm(residuals, axis=1))
                if max_norm > lambda_ + tol:
                    raise ValueError(
                        f"Contractivity check failed at level {level}: "
                        f"max_k ||r(x)_k||_2 = {max_norm:.6e} > lambda_ = {lambda_:.6e}."
                    )

            children = x[None, :] + level_scale * residuals
            children_list.append(children)

        if len(children_list) == 0:
            levels.append(np.empty((0, d)))
        else:
            levels.append(np.vstack(children_list))

    return levels

