# Benchmark 4: Random Affine IFS  (configurable K, d)
# ============================================================

def generate_random_affine_ifs(
    K=3,
    d=2,
    depth=7,
    x0=None,
    contraction_range=(0.2, 0.45),
    noise_std=0.0,
    seed=None,
):
    """
    Random Barnsley-style affine IFS.  For each of the K maps:
        f_k(x) = s_k R(θ_k) x + b_k
    where s_k ~ Uniform(*contraction_range), θ_k ~ Uniform(0, 2π),
    b_k ~ Uniform(-0.5, 0.5)^d.

    The IFS family is fixed within a single benchmark instance but varies
    across trials (via seed).
    """
    rng = np.random.default_rng(seed)

    contractions = rng.uniform(*contraction_range, size=K)
    angles = rng.uniform(0, 2 * np.pi, size=K)
    translations = rng.uniform(-0.5, 0.5, size=(K, d))

    maps = []
    A_list = []
    for k in range(K):
        c, sn = np.cos(angles[k]), np.sin(angles[k])
        R = np.array([[c, -sn], [sn, c]]) if d == 2 else np.eye(d)
        A_k = contractions[k] * R
        A_list.append(A_k)
        maps.append(make_affine_map(A_k, translations[k]))

    if x0 is None:
        x0 = np.zeros(d)

    levels = build_ifs_hierarchy(maps, x0, depth, noise_std, seed)

    return make_benchmark_dict(
        name="random_affine_ifs",
        levels=levels,
        K=K,
        maps=maps,
        metadata={
            "contractions": contractions,
            "angles": angles,
            "translations": translations,
            "A_matrices": A_list,
            "seed": seed,
        },
    )


