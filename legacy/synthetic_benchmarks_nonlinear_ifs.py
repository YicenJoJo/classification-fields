# Benchmark 3: Koch Curve  (K=4, d=2)
# ============================================================

def generate_koch_curve(depth=5, x0=None, noise_std=0.0, seed=None):
    """
    Koch curve via the 4-map IFS:
        f_1(x) = x/3
        f_2(x) = R(60°) x/3 + (1/3, 0)
        f_3(x) = R(-60°) x/3 + (1/2, √3/6)
        f_4(x) = x/3 + (2/3, 0)

    The residuals involve nontrivial rotations, testing whether the model
    can learn geometric transformations beyond simple translations.
    """
    c = np.cos(np.pi / 3)
    sn = np.sin(np.pi / 3)

    R60 = np.array([[c, -sn], [sn, c]])
    Rm60 = np.array([[c, sn], [-sn, c]])

    maps = [
        make_affine_map(np.eye(2) / 3, np.array([0.0, 0.0])),
        make_affine_map(R60 / 3, np.array([1.0 / 3, 0.0])),
        make_affine_map(Rm60 / 3, np.array([0.5, np.sqrt(3) / 6])),
        make_affine_map(np.eye(2) / 3, np.array([2.0 / 3, 0.0])),
    ]

    if x0 is None:
        x0 = np.array([0.5, 0.0])

    levels = build_ifs_hierarchy(maps, x0, depth, noise_std, seed)

    return make_benchmark_dict(
        name="koch_curve",
        levels=levels,
        K=4,
        maps=maps,
        metadata={"contraction": 1.0 / 3},
    )


