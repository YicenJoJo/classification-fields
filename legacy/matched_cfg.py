def run_repeated_extrapolation_experiment(
    n_trials=10,
    L_train=2,
    n_extra_levels=6,
    d=2,
    K=3,
    scale=0.75,
    lambda_=None,
    x0=None,
    C_radius=1.0,
    nu=3.25,
    sigma_min=0.1,
    sigma_max=1.0,
    hidden_dim_rhg=500,
    hidden_width=64,
    depth=3,
    lr=1e-3,
    epochs=3000,
    print_every=300,
    verbose=True,
    device=None,
):
    if device is None:
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print("Using device:", device)

    if x0 is None:
        x0 = np.zeros(d, dtype=float)
    else:
        x0 = np.asarray(x0, dtype=float).reshape(d)

    L_total = L_train + n_extra_levels
    extrap_levels = np.arange(L_train + 1, L_total + 1)

    methods = ["avg_baseline", "constant", "linear", "nn"]
    collectors = {m: [] for m in methods}
    trial_metadata = []

    for trial in range(n_trials):
        seed_C = 1000 + trial
        seed_r = 2000 + trial

        C = get_C(d=d, K=K, radius=C_radius, seed=seed_C)

        r_col, r = get_RHG(
            C=C,
            nu=nu,
            sigma_min=sigma_min,
            sigma_max=sigma_max,
            hidden_dim=hidden_dim_rhg,
            seed=seed_r,
        )

        levels = build_hierarchy(
            r,
            x0,
            max_level=L_total,
            scale=scale,
            lambda_=lambda_,
            check_contractivity=(lambda_ is not None),
        )

        # --- 1. Average residual baseline (non-learnable) ---
        avg_residuals = estimate_average_residuals(
            levels, L_train=L_train, K=K, scale=scale,
        )
        levels_hat_avg = build_hierarchy_from_average_residuals(
            avg_residuals, x0, max_level=L_total, scale=scale,
        )
        collectors["avg_baseline"].append([
            np.mean((levels_hat_avg[l] - levels[l]) ** 2) for l in extrap_levels
        ])

        # --- 2. Learnable constant baseline ---
        model_const = train_hrg_model(
            ConstantHRG(d=d, K=K), levels, x0=x0,
            L_train=L_train, n_extra_levels=n_extra_levels,
            K=K, scale=scale, lr=lr, epochs=epochs,
            print_every=print_every, device=device,
        )
        levels_hat_const = build_hierarchy_from_model(
            model_const, x0, max_level=L_total, scale=scale,
        )
        collectors["constant"].append([
            np.mean((levels_hat_const[l] - levels[l]) ** 2) for l in extrap_levels
        ])

        # --- 3. Linear (affine) baseline ---
        model_lin = train_hrg_model(
            LinearHRG(d=d, K=K), levels, x0=x0,
            L_train=L_train, n_extra_levels=n_extra_levels,
            K=K, scale=scale, lr=lr, epochs=epochs,
            print_every=print_every, device=device,
        )
        levels_hat_lin = build_hierarchy_from_model(
            model_lin, x0, max_level=L_total, scale=scale,
        )
        collectors["linear"].append([
            np.mean((levels_hat_lin[l] - levels[l]) ** 2) for l in extrap_levels
        ])

        # --- 4. NN (ours) ---
        # Uses the same optimizer / scheduler / grad_clip as baselines for fair comparison.
        model_nn = train_hrg_model(
            HRGMLP(d=d, K=K, hidden_width=hidden_width, depth=depth),
            levels, x0=x0,
            L_train=L_train, n_extra_levels=n_extra_levels,
            K=K, scale=scale, lr=lr, epochs=epochs,
            print_every=print_every, device=device,
        )
        levels_hat_nn = build_hierarchy_from_model(
            model_nn, x0, max_level=L_total, scale=scale,
        )
        collectors["nn"].append([
            np.mean((levels_hat_nn[l] - levels[l]) ** 2) for l in extrap_levels
        ])

        trial_metadata.append({
            "trial": trial,
            "seed_C": seed_C,
            "seed_r": seed_r,
            "avg_residuals": avg_residuals.copy(),
            "levels_train": [lev.copy() for lev in levels[:L_train + 1]],
        })

        if verbose:
            print(f"\nTrial {trial + 1}/{n_trials}")
            print(f"  seed_C = {seed_C}, seed_r = {seed_r}")
            for idx, l in enumerate(extrap_levels):
                parts = "  ".join(
                    f"{m}={collectors[m][-1][idx]:.4e}" for m in methods
                )
                print(f"  Level {l}: {parts}")

        if device.type == "cuda":
            torch.cuda.empty_cache()

    # Aggregate all methods into a unified results dict
    results = {
        "levels": extrap_levels,
        "trial_metadata": trial_metadata,
    }
    for m in methods:
        arr = np.array(collectors[m], dtype=float)
        results[f"{m}_mse_trials"] = arr
        results[f"{m}_mean"] = arr.mean(axis=0)
        results[f"{m}_std"] = (arr.std(axis=0, ddof=1) if n_trials > 1
                               else np.zeros_like(extrap_levels, dtype=float))

    # Backward-compatible aliases: "baseline" (old) -> "avg_baseline" (new)
    results["baseline_mse_trials"] = results["avg_baseline_mse_trials"]
    results["baseline_mean"] = results["avg_baseline_mean"]
    results["baseline_std"] = results["avg_baseline_std"]

    return results

