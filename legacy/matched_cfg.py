def adjust_color(color, factor):
    """
    factor > 1  => lighten
    factor < 1  => darken
    """
    rgb = np.array(mcolors.to_rgb(color))
    if factor >= 1:
        return tuple(np.clip(1 - (1 - rgb) / factor, 0, 1))
    return tuple(np.clip(rgb * factor, 0, 1))

def get_future_level_colors(l, K=3):
    """
    Return K evenly-spaced shades for future predicted level l.
    Picks a base color by level and varies brightness across children.
    """
    base_cycle = [
        "purple",
        "royalblue",
        "darkorange",
        "teal",
        "goldenrod",
        "brown",
        "slategray",
    ]
    base = base_cycle[(l - 3) % len(base_cycle)]
    if K == 1:
        return [adjust_color(base, 1.0)]
    # Spread brightness from 1.35 (lightest) to 0.70 (darkest) across K.
    factors = np.linspace(1.35, 0.70, K)
    return [adjust_color(base, f) for f in factors]

