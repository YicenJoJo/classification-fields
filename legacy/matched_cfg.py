def train_hrg_mlp(
    levels,
    x0=None,
    L_train=None,
    n_extra_levels=1,
    d=2,
    K=3,
    scale=1.0,
    hidden_width=64,
    depth=3,
    lr=1e-3,
    epochs=2000,
    print_every=200,
    return_history=False,
    device=None,
):
    """
    Train \hat r from hierarchy data observed up to level L_train.

    Parameters
    ----------
    levels : list of np.ndarray
        Full true hierarchy [H_0, ..., H_L].
    x0 : np.ndarray or None
        Root used for rollout during out-of-sample testing.
        Required if test MSE is requested.
    L_train : int or None
        Observed training depth. The model is trained only on
        [H_0, ..., H_{L_train}]. If None, defaults to len(levels)-1.
    n_extra_levels : int, default=1
        Number of levels to extrapolate beyond L_train for testing.
        Test MSE is reported only at the target level H_{L_train+n_extra_levels}.
    return_history : bool, default=False
        If True, also return a dict containing train/test MSE histories.
    """
    if L_train is None:
        L_train = len(levels) - 1

    if L_train < 1:
        raise ValueError("L_train must be at least 1.")

    if L_train >= len(levels):
        raise ValueError(
            f"L_train must satisfy L_train < len(levels), got "
            f"L_train={L_train}, len(levels)={len(levels)}."
        )

    target_level = L_train + n_extra_levels
    can_test = (
        x0 is not None
        and n_extra_levels is not None
        and n_extra_levels >= 1
        and target_level < len(levels)
    )

    if device is None:
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    train_levels = levels[:L_train + 1]
    X, Y, S = hierarchy_to_training_data(train_levels, K=K, scale=scale)
    X, Y, S = X.to(device), Y.to(device), S.to(device)

    model = HRGMLP(d=d, K=K, hidden_width=hidden_width, depth=depth).to(device)
    optimizer = optim.Adam(model.parameters(), lr=lr)

    history = {
        "epoch": [],
        "train_mse": [],
        "test_mse": [],
        "L_train": L_train,
        "target_level": target_level if can_test else None,
    }

    for epoch in range(1, epochs + 1):
        model.train()
        optimizer.zero_grad()
        loss = hierarchy_loss(model, X, Y, S)
        loss.backward()
        optimizer.step()

        is_log_epoch = (epoch % print_every == 0 or epoch == 1 or epoch == epochs)

        with torch.no_grad():
            model.eval()
            pred_train = X.unsqueeze(1) + S * model(X)
            train_mse = ((pred_train - Y) ** 2).mean().item()

            test_mse = None
            if can_test and is_log_epoch:
                levels_hat_eval = build_hierarchy_from_model(
                    model,
                    x0,
                    max_level=target_level,
                    scale=scale,
                )
                pred_target = levels_hat_eval[target_level]
                true_target = levels[target_level]
                test_mse = np.mean((pred_target - true_target) ** 2)

        history["epoch"].append(epoch)
        history["train_mse"].append(train_mse)
        history["test_mse"].append(test_mse)

        if is_log_epoch:
            if test_mse is None:
                print(
                    f"Epoch {epoch:5d} | Loss = {loss.item():.8f} | "
                    f"Train MSE = {train_mse:.8f}"
                )
            else:
                print(
                    f"Epoch {epoch:5d} | Loss = {loss.item():.8f} | "
                    f"Train MSE = {train_mse:.8f} | "
                    f"Test MSE@Level {target_level} = {test_mse:.8f}"
                )

    model.training_history = history

    if return_history:
        return model, history
    return model


