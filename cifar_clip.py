# ============================================================
# 1. Build supervised training data from hierarchy levels
# ============================================================

def hierarchy_to_training_data(levels, K=3, scale=1.0):
    """
    Convert hierarchy levels [H_0, ..., H_L] into supervised data.

    Parameters
    ----------
    levels : list of np.ndarray
        levels[l] has shape (n_l, d), where n_l = K^l in the full-tree case.
    K : int
        Number of children per parent.
    scale : float, default=1.0
        Scaling factor s. A parent at level l generates children via
            x + s^l r(x)_k.

    Returns
    -------
    X : torch.Tensor, shape (N, d)
        Parent nodes.
    Y : torch.Tensor, shape (N, K, d)
        Corresponding children of each parent.
    S : torch.Tensor, shape (N, 1, 1)
        Per-sample scaling factors s^l, where l is the level of the parent.
    """
    if not (0 < scale <= 1):
        raise ValueError(f"scale must satisfy 0 < scale <= 1, but got {scale}.")

    X_list = []
    Y_list = []
    S_list = []

    for l in range(len(levels) - 1):
        parents = levels[l]        # shape (n_l, d)
        children = levels[l + 1]   # shape (n_{l+1}, d)

        n_parents, d = parents.shape

        if children.shape[0] != n_parents * K:
            raise ValueError(
                f"Level {l+1} should have {n_parents*K} nodes, "
                f"but got {children.shape[0]}."
            )

        # By construction in build_hierarchy, children are ordered parent-by-parent
        children_grouped = children.reshape(n_parents, K, d)

        X_list.append(parents)
        Y_list.append(children_grouped)

        level_scales = np.full((n_parents, 1, 1), scale ** (l + 1), dtype=np.float32)
        S_list.append(level_scales)

    X = np.vstack(X_list)                  # (N, d)
    Y = np.vstack(Y_list)                  # (N, K, d)
    S = np.vstack(S_list)                  # (N, 1, 1)

    return (
        torch.tensor(X, dtype=torch.float32),
        torch.tensor(Y, dtype=torch.float32),
        torch.tensor(S, dtype=torch.float32),
    )


