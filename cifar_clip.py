# 2. MLP for residual generator \hat r : R^d -> R^{dK}
# ============================================================

class HRGMLP(nn.Module):
    def __init__(self, d=2, K=3, hidden_width=64, depth=3):
        super().__init__()
        layers = []

        in_dim = d
        for _ in range(depth):
            layers.append(nn.Linear(in_dim, hidden_width))
            layers.append(nn.ReLU())
            in_dim = hidden_width

        layers.append(nn.Linear(in_dim, d * K))
        self.net = nn.Sequential(*layers)

        self.d = d
        self.K = K

    def forward(self, x):
        """
        x: shape (batch, d)
        returns: shape (batch, K, d)
        """
        out = self.net(x)                  # (batch, d*K)
        return out.view(-1, self.K, self.d)


class BottleneckHRGMLP(nn.Module):
    """HRG MLP with information bottleneck: expand → wide body → contract.

    Architecture for a given depth n (hidden layers):
      Layer 1:       d     → wide   (expand)
      Layers 2..n-1: wide  → wide   (maintain)
      Layer n:       wide  → d      (contract / bottleneck)
      Output:        d     → d * K
    """
    ACT_MAP = {
        "relu":       lambda: nn.ReLU(),
        "leaky_relu": lambda: nn.LeakyReLU(0.01),
        "gelu":       lambda: nn.GELU(),
        "silu":       lambda: nn.SiLU(),
    }

    def __init__(self, d=512, K=3, wide=1024, depth=5,
                 act_type="gelu", use_layernorm=False):
        super().__init__()
        assert depth >= 2, "Need at least 2 hidden layers for bottleneck"
        make_act = self.ACT_MAP.get(act_type, self.ACT_MAP["gelu"])
        self.act_type = act_type
        layers = []
        layers.append(nn.Linear(d, wide))
        if use_layernorm:
            layers.append(nn.LayerNorm(wide))
        layers.append(make_act())
        for _ in range(depth - 2):
            layers.append(nn.Linear(wide, wide))
            if use_layernorm:
                layers.append(nn.LayerNorm(wide))
            layers.append(make_act())
        layers.append(nn.Linear(wide, d))
        if use_layernorm:
            layers.append(nn.LayerNorm(d))
        layers.append(make_act())
        layers.append(nn.Linear(d, d * K))
        self.net = nn.Sequential(*layers)
        self.d = d
        self.K = K
        self._init_weights()

    def _init_weights(self):
        nonlin = "leaky_relu" if self.act_type in ("leaky_relu", "gelu", "silu") else "relu"
        for m in self.net:
            if isinstance(m, nn.Linear):
                nn.init.kaiming_normal_(m.weight, nonlinearity=nonlin)
                if m.bias is not None:
                    nn.init.zeros_(m.bias)
        last_linear = self.net[-1]
        nn.init.xavier_uniform_(last_linear.weight)

    def forward(self, x):
        out = self.net(x)
        return out.view(-1, self.K, self.d)


# ============================================================
# 2b. Learnable constant residual model: r_hat(x)_k = c_k
# ============================================================

class ConstantHRG(nn.Module):
    """
    Location-independent learnable residual generator.
    The K residual vectors c_1, ..., c_K are free parameters that do not
    depend on the input x.
    """
    def __init__(self, d=2, K=3):
        super().__init__()
        self.d = d
        self.K = K
        self.residuals = nn.Parameter(torch.randn(K, d) * 0.1)

    def forward(self, x):
        return self.residuals.unsqueeze(0).expand(x.shape[0], -1, -1)


# ============================================================
# 2c. Linear (affine) residual model: r_hat(x)_k = A_k x + b_k
# ============================================================

class LinearHRG(nn.Module):
    """
    Affine residual generator.  Maps x -> K*d outputs via a single linear
    layer (no hidden layers, no activation), then reshapes to (K, d).
    """
    def __init__(self, d=2, K=3):
        super().__init__()
        self.d = d
        self.K = K
        self.linear = nn.Linear(d, d * K)

    def forward(self, x):
        return self.linear(x).view(-1, self.K, self.d)


# ============================================================
# 2d. Generic training loop for any model with
#     forward(x) -> (batch, K, d) interface
# ============================================================

def train_hrg_model(
    model,
    levels,
    x0=None,
    L_train=None,
    n_extra_levels=1,
    K=3,
    scale=1.0,
    lr=1e-3,
    epochs=2000,
    print_every=200,
    device=None,
    grad_clip=1.0,
    use_scheduler=True,
    weight_decay=0.0,
):
    """
    Train an arbitrary residual-generator model using hierarchy_loss.
    Accepts any nn.Module with forward(x) -> (batch, K, d).
    """
    if L_train is None:
        L_train = len(levels) - 1
    if device is None:
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    target_level = L_train + n_extra_levels
    can_test = (
        x0 is not None and n_extra_levels >= 1
        and target_level < len(levels)
    )

    train_levels = levels[:L_train + 1]
    X, Y, S = hierarchy_to_training_data(train_levels, K=K, scale=scale)
    X, Y, S = X.to(device), Y.to(device), S.to(device)

    model = model.to(device)
    optimizer = optim.Adam(model.parameters(), lr=lr, weight_decay=weight_decay)
    scheduler = None
    if use_scheduler:
        scheduler = optim.lr_scheduler.CosineAnnealingLR(
            optimizer, T_max=epochs, eta_min=lr * 0.01,
        )

    for epoch in range(1, epochs + 1):
        model.train()
        optimizer.zero_grad()
        loss = hierarchy_loss(model, X, Y, S)
        loss.backward()
        if grad_clip > 0:
            torch.nn.utils.clip_grad_norm_(model.parameters(), grad_clip)
        optimizer.step()
        if scheduler is not None:
            scheduler.step()

        is_log_epoch = (epoch % print_every == 0 or epoch == 1 or epoch == epochs)
        if is_log_epoch:
            with torch.no_grad():
                model.eval()
                pred_train = X.unsqueeze(1) + S * model(X)
                train_mse = ((pred_train - Y) ** 2).mean().item()
                test_str = ""
                if can_test:
                    lh = build_hierarchy_from_model(
                        model, x0, max_level=target_level, scale=scale,
                    )
                    test_mse = np.mean((lh[target_level] - levels[target_level]) ** 2)
                    test_str = f" | Test MSE@L{target_level} = {test_mse:.8f}"
                cur_lr = optimizer.param_groups[0]['lr']
                print(f"Epoch {epoch:5d} | Loss = {loss.item():.8f} | "
                      f"Train MSE = {train_mse:.8f}{test_str} | lr={cur_lr:.2e}")

    model.eval()
    return model


# ============================================================
# 3. Loss corresponding to
#    sum || x + s^l \hat r(x)_k - chld(x)_k ||^2
# ============================================================

def hierarchy_loss(model, X, Y, S):
    """
    X: (N, d)        parent nodes
    Y: (N, K, d)     observed children
    S: (N, 1, 1)     scaling factors s^l attached to each parent

    returns scalar loss
    """
    pred_residuals = model(X)                     # (N, K, d)
    pred_children = X.unsqueeze(1) + S * pred_residuals
    return ((pred_children - Y) ** 2).sum()


