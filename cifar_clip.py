SCP_K             = 3       # branching factor: each SCP splits into K clusters
SCP_MAX_DEPTH     = 7       # total tree depth (levels 0..7)
SCP_L_TRAIN       = 5       # train HRG on levels 0..L_TRAIN
SCP_N_EXTRA       = 2       # held-out levels 6 and 7
SCP_SCALE         = 0.9     # residual scaling factor for HRG
SCP_MIN_CLUSTER   = 50      # stop splitting if cluster < this many samples
SCP_EPOCHS        = 30      # training epochs per SCP cluster head
SCP_LR            = 0.001   # SCP learning rate
SCP_BATCH_SIZE    = 512     # SCP training batch size
HRG_HIDDEN_WIDTH  = 1024    # BottleneckHRGMLP wide dimension
HRG_DEPTH         = 7       # BottleneckHRGMLP depth (hidden layers)
HRG_ACT_TYPE      = "gelu"  # BottleneckHRGMLP activation function
HRG_LR            = 1e-3    # HRG learning rate
HRG_EPOCHS        = 3000    # HRG training epochs
HRG_PRINT_EVERY   = 300     # print loss every N epochs
CLIP_BATCH_SIZE   = 256     # batch size for CLIP feature extraction
CIFAR_N_TRIALS    = int(os.environ.get("EXP_CIFAR_N_TRIALS", "5"))
CIFAR_BASE_SEED   = int(os.environ.get("EXP_CIFAR_BASE_SEED", "42"))
# -------------------------------------

all_trial_rows = []
last_results = {}

for trial in range(CIFAR_N_TRIALS):
    seed = CIFAR_BASE_SEED + trial
    print("\n" + "#" * 80)
    print(f"# CIFAR SCP TRIAL {trial + 1}/{CIFAR_N_TRIALS} | seed={seed}")
    print("#" * 80)

    set_seed(seed)
    scp_results_100 = run_cifar_scp_hierarchy_experiment(
        dataset_name="cifar100",
        K=SCP_K,
        max_depth=SCP_MAX_DEPTH,
        L_train=SCP_L_TRAIN,
        n_extra_levels=SCP_N_EXTRA,
        scale=SCP_SCALE,
        min_cluster_size=SCP_MIN_CLUSTER,
        scp_epochs=SCP_EPOCHS,
        scp_lr=SCP_LR,
        scp_batch_size=SCP_BATCH_SIZE,
        hidden_width=HRG_HIDDEN_WIDTH,
        depth=HRG_DEPTH,
        act_type=HRG_ACT_TYPE,
        lr=HRG_LR,
        epochs=HRG_EPOCHS,
        print_every=HRG_PRINT_EVERY,
        batch_size=CLIP_BATCH_SIZE,
        device=device,
    )
    all_trial_rows.extend(_collect_cifar_metric_rows(scp_results_100, trial, seed))
    last_results["cifar100"] = scp_results_100

    print("\n" + "#" * 80)
    print(f"# CIFAR-10 SCP EXPERIMENT | trial {trial + 1}/{CIFAR_N_TRIALS} | seed={seed}")
    print("#" * 80)

    set_seed(seed)
    scp_results_10 = run_cifar_scp_hierarchy_experiment(
        dataset_name="cifar10",
        K=SCP_K,
        max_depth=SCP_MAX_DEPTH,
        L_train=SCP_L_TRAIN,
        n_extra_levels=SCP_N_EXTRA,
        scale=SCP_SCALE,
        min_cluster_size=SCP_MIN_CLUSTER,
        scp_epochs=SCP_EPOCHS,
        scp_lr=SCP_LR,
        scp_batch_size=SCP_BATCH_SIZE,
        hidden_width=HRG_HIDDEN_WIDTH,
        depth=HRG_DEPTH,
        act_type=HRG_ACT_TYPE,
        lr=HRG_LR,
        epochs=HRG_EPOCHS,
        print_every=HRG_PRINT_EVERY,
        batch_size=CLIP_BATCH_SIZE,
        device=device,
    )
    all_trial_rows.extend(_collect_cifar_metric_rows(scp_results_10, trial, seed))
    last_results["cifar10"] = scp_results_10

_write_cifar_trial_metrics(
    all_trial_rows,
    out_path=f"{OUTPUT_DIR}/cifar_scp_5seed_trials.csv",
)
_write_cifar_multiseed_summary(
    all_trial_rows,
    out_path=f"{OUTPUT_DIR}/cifar_scp_5seed_summary.csv",
)


# ==============================================================
