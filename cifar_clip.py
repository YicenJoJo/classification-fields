def tree_to_levels(tree, target_depth=None):
    """
    Convert a recursive K-ary tree into the levels format expected by
    hierarchy_to_training_data(...).

    The tree must be a proper full K-ary tree up to target_depth:
    every internal node must have exactly K children (K auto-detected).

    Parameters
    ----------
    tree : dict
        Output of build_recursive_kmeans_hierarchy or
        build_recursive_scp_hierarchy.
    target_depth : int or None
        If given, only include levels 0..target_depth.  If None,
        include all levels up to the maximum full depth found.

    Returns
    -------
    levels : list of np.ndarray
        levels[l] has shape (K^l, d).
    """
    if target_depth is None:
        target_depth = _tree_max_full_depth(tree)

    levels = []
    current_nodes = [tree]

    for depth in range(target_depth + 1):
        centroids = np.array([n["centroid"] for n in current_nodes])
        levels.append(centroids)

        if depth < target_depth:
            next_nodes = []
            for n in current_nodes:
                if n["children"] is None or len(n["children"]) == 0:
                    raise ValueError(
                        f"Node at depth {depth} is a leaf but target_depth "
                        f"requires children.  Reduce target_depth or ensure "
                        f"the tree is full up to the desired depth."
                    )
                next_nodes.extend(n["children"])
            current_nodes = next_nodes

    return levels


def _tree_max_full_depth(tree, K=None):
    """Find the maximum depth at which every node has exactly K children.
    If K is None, accept any non-zero child count (auto-detect from root)."""
    if tree["children"] is None or len(tree["children"]) == 0:
        return 0
    if K is not None and len(tree["children"]) != K:
        return 0
    actual_k = len(tree["children"])
    child_depths = [_tree_max_full_depth(c, K=actual_k) for c in tree["children"]]
    return 1 + min(child_depths)


# ============================================================
# Step 5.  PCA-based canonical child ordering
# ============================================================

def canonicalize_levels_pca(levels, K=3, pca_model=None):
    """
    Reorder each parent's children using a PCA-based angle rule.

    For each parent at level l:
      1. Project (child - parent) onto the first 2 PCA components.
      2. Sort by polar angle (atan2), with distance as tie-breaker.

    Parameters
    ----------
    levels : list of np.ndarray
    K : int
        Branching factor of the hierarchy.
    pca_model : sklearn PCA or None
        If None, a PCA is fitted on all centroids across all levels.

    Returns
    -------
    levels_canon : list of np.ndarray
    """
    if pca_model is None:
        all_centroids = np.vstack(levels)
        pca_model = PCA(n_components=min(2, all_centroids.shape[1]))
        pca_model.fit(all_centroids)

    levels_canon = [lev.copy() for lev in levels]

    for l in range(1, len(levels_canon)):
        n_parents = levels_canon[l - 1].shape[0]
        new_order = np.empty(n_parents * K, dtype=int)

        for p in range(n_parents):
            parent = levels_canon[l - 1][p]
            start = p * K
            children = levels_canon[l][start: start + K]

            disp = children - parent
            disp_2d = pca_model.transform(disp)[:, :2]

            angles = np.arctan2(disp_2d[:, 1], disp_2d[:, 0])
            dists = np.linalg.norm(disp, axis=1)
            sort_idx = np.lexsort((dists, angles))

            new_order[start: start + K] = start + sort_idx

        levels_canon[l] = levels_canon[l][new_order]

    return levels_canon


