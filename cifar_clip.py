def run_cifar_scp_hierarchy_experiment(
    dataset_name="cifar100",
    K=3,
    max_depth=5,
    L_train=3,
    n_extra_levels=2,
    scale=0.9,
    min_cluster_size=50,
    scp_epochs=30,
    scp_lr=0.001,
    scp_batch_size=512,
    hidden_width=1024,
    depth=5,
    act_type="gelu",
    lr=1e-3,
    epochs=3000,
    print_every=300,
    batch_size=256,
    device=None,
):
    """
    End-to-end CIFAR + CLIP + SCP hierarchy experiment (supports CIFAR-10/100).

    Steps:
      1. Extract augmented CLIP embeddings (two views).
      2. Build recursive SCP (cluster_num=K) hierarchy.
      3. Convert to levels, apply PCA canonical ordering.
      4. Train HRG MLP + Linear baseline + Avg Residual baseline.
      5. Evaluate at extrapolation levels (matched + slot-wise MSE).
      6. Print label-purity diagnostic.
    """
    if device is None:
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Device: {device}")

    ds_tag = dataset_name.upper()
    # --- 1. Embeddings ---
    print(f"\n[Step 1] [{ds_tag}] Extracting augmented CLIP embeddings...")
    feat_q, feat_k, fine_labels, coarse_labels = (
        extract_clip_embeddings_augmented(
            dataset_name=dataset_name,
            dataset_split="train",
            clip_model_name="ViT-B/32",
            batch_size=batch_size,
            device=device,
        )
    )
    d_embed = feat_q.shape[1]
    print(f"  Embedding dim = {d_embed}")

    # --- 2. Build SCP hierarchy ---
    print(f"\n[Step 2] Building recursive SCP hierarchy "
          f"(K={K}, max_depth={max_depth})...")
    tree = build_recursive_scp_hierarchy(
        feat_q, feat_k,
        cluster_num=K,
        max_depth=max_depth,
        min_cluster_size=min_cluster_size,
        scp_epochs=scp_epochs,
        scp_lr=scp_lr,
        scp_batch_size=scp_batch_size,
        sort_children=True,
        device=device,
    )

    full_depth = _tree_max_full_depth(tree)
    L_total = min(full_depth, max_depth)
    print(f"  Max full {K}-ary depth = {full_depth}")
    print(f"  Using L_total = {L_total}")

    if L_train >= L_total:
        raise ValueError(
            f"L_train={L_train} >= L_total={L_total}. "
            f"Increase max_depth or decrease L_train."
        )
    if L_train + n_extra_levels > L_total:
        n_extra_levels = L_total - L_train
        print(f"  Clamped n_extra_levels to {n_extra_levels}")

    # --- 3. Convert to levels + canonicalize ---
    print(f"\n[Step 3] Converting tree to levels and canonicalizing...")
    levels = tree_to_levels(tree, target_depth=L_total)

    all_centroids = np.vstack(levels)
    pca_model = PCA(n_components=min(2, d_embed))
    pca_model.fit(all_centroids)
    levels = canonicalize_levels_pca(levels, K=K, pca_model=pca_model)

    for l, H_l in enumerate(levels):
        print(f"  Level {l}: {H_l.shape[0]} nodes, shape {H_l.shape}")

    x0 = levels[0][0]

    # --- 4. Train BottleneckHRGMLP (GELU) ---
    print(f"\n[Step 4] Training BottleneckHRGMLP "
          f"(act={act_type}, depth={depth}, wide={hidden_width}, "
          f"L_train={L_train}, extrapolate to level {L_train + n_extra_levels})...")
    model_nn = BottleneckHRGMLP(
        d=d_embed, K=K, wide=hidden_width, depth=depth,
        act_type=act_type,
    )
    n_params = sum(p.numel() for p in model_nn.parameters())
    print(f"  Parameters: {n_params:,}")
    model_nn = train_hrg_model(
        model_nn, levels, x0=x0,
        L_train=L_train, n_extra_levels=n_extra_levels,
        K=K, scale=scale, lr=lr, epochs=epochs,
        print_every=print_every, device=device,
    )
    levels_hat_nn = build_hierarchy_from_model(
        model_nn, x0, max_level=L_total, scale=scale,
    )

    # --- 5. Average residual baseline ---
    print(f"\n[Step 5] Computing average residual baseline...")
    avg_residuals = estimate_average_residuals(
        levels, L_train=L_train, K=K, scale=scale,
    )
    levels_hat_avg = build_hierarchy_from_average_residuals(
        avg_residuals, x0, max_level=L_total, scale=scale,
    )

    # --- 6. Linear Residual Generator baseline ---
    print(f"\n[Step 6] Training Linear Residual Generator...")
    model_lin = train_hrg_model(
        LinearHRG(d=d_embed, K=K), levels, x0=x0,
        L_train=L_train, n_extra_levels=n_extra_levels,
        K=K, scale=scale, lr=lr, epochs=epochs,
        print_every=print_every, device=device,
    )
    levels_hat_lin = build_hierarchy_from_model(
        model_lin, x0, max_level=L_total, scale=scale,
    )

    # --- 7. Learnable Constant baseline ---
    print(f"\n[Step 7] Training Learnable Constant baseline...")
    model_const = train_hrg_model(
        ConstantHRG(d=d_embed, K=K), levels, x0=x0,
        L_train=L_train, n_extra_levels=n_extra_levels,
        K=K, scale=scale, lr=lr, epochs=epochs,
        print_every=print_every, device=device,
    )
    levels_hat_const = build_hierarchy_from_model(
        model_const, x0, max_level=L_total, scale=scale,
    )

    # --- 8. Metrics: Ordered MSE, Symmetric Chamfer, d_pt-Distortion ---
    print(f"\n[Step 8] Metrics")
    print("=" * 130)

    heldout_end = min(L_train + n_extra_levels, L_total)
    extrap_levels = list(range(L_train + 1, heldout_end + 1))
    method_hats = {
        "CFP": levels_hat_nn,
        "Avg Residual": levels_hat_avg,
        "Linear Res Gen": levels_hat_lin,
        "Constant": levels_hat_const,
    }

    results = {
        "dataset_name": dataset_name,
        "levels": levels,
        "levels_hat_nn": levels_hat_nn,
        "levels_hat_avg": levels_hat_avg,
        "levels_hat_lin": levels_hat_lin,
        "levels_hat_const": levels_hat_const,
        "K": K,
        "L_train": L_train,
        "L_total": L_total,
        "d_embed": d_embed,
        "hrg_depth": depth,
        "tree": tree,
        "fine_labels": fine_labels,
        "coarse_labels": coarse_labels,
        "extrap_metrics": {},
        "heldout_levels": extrap_levels,
        "heldout_avg_metrics": {},
    }

    hdr = (f"{'Level':<8} {'Method':<18} {'Ordered MSE':>14} "
           f"{'SymChamfer':>14} {'d_pt-Distort':>14}")
    print(hdr)
    print("-" * 130)

    for lv in extrap_levels:
        true_lv = levels[lv]
        lv_metrics = {}

        for mname, hat_levels in method_hats.items():
            pred_lv = hat_levels[lv]
            ord_mse = float(np.mean((pred_lv - true_lv) ** 2))
            cham = chamfer_distance(pred_lv, true_lv)
            dpt = dpt_distortion(hat_levels, levels, K, upto_level=lv,
                                 normalize="diameter")
            print(f"  {lv:<6} {mname:<18} {ord_mse:>14.6e} "
                  f"{cham:>14.6e} {dpt:>14.6e}")
            lv_metrics[mname] = {
                "ordered_mse": ord_mse,
                "pi_chamfer": cham,
                "dpt_distortion": dpt,
            }
        results["extrap_metrics"][lv] = lv_metrics
        print()

    print(f"Held-out average over levels {extrap_levels}:")
    for mname in method_hats:
        method_avg = {}
        for metric_name in ("ordered_mse", "pi_chamfer", "dpt_distortion"):
            vals = [
                results["extrap_metrics"][lv][mname][metric_name]
                for lv in extrap_levels
            ]
            method_avg[metric_name] = float(np.mean(vals))
        results["heldout_avg_metrics"][mname] = method_avg
        print(f"  {'mean':<6} {mname:<18} "
              f"{method_avg['ordered_mse']:>14.6e} "
              f"{method_avg['pi_chamfer']:>14.6e} "
              f"{method_avg['dpt_distortion']:>14.6e}")

    print("=" * 130)

    import csv
    csv_path = f"{OUTPUT_DIR}/{dataset_name}_scp_metrics.csv"
    with open(csv_path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["level", "method", "ordered_mse", "pi_chamfer",
                     "dpt_distortion"])
        for lv in extrap_levels:
            for mname, m in results["extrap_metrics"][lv].items():
                w.writerow([lv, mname, f"{m['ordered_mse']:.6e}",
                            f"{m['pi_chamfer']:.6e}",
                            f"{m['dpt_distortion']:.6e}"])
        for mname, m in results["heldout_avg_metrics"].items():
            level_tag = "mean_" + "_".join(str(lv) for lv in extrap_levels)
            w.writerow([level_tag, mname, f"{m['ordered_mse']:.6e}",
                        f"{m['pi_chamfer']:.6e}",
                        f"{m['dpt_distortion']:.6e}"])
    print(f"Saved: {csv_path}")

    # --- 8. Label purity ---
    print(f"\n[Step 9] Label purity diagnostic")
    for lv in range(L_total + 1):
        purities_fine = compute_cluster_purity(tree, fine_labels, lv)
        if not purities_fine:
            continue
        avg_fine = np.mean([p for _, p, _ in purities_fine])
        n_clusters = len(purities_fine)
        msg = f"  Level {lv}: {n_clusters} clusters | Fine purity = {avg_fine:.3f}"
        if coarse_labels is not None:
            purities_coarse = compute_cluster_purity(tree, coarse_labels, lv)
            avg_coarse = np.mean([p for _, p, _ in purities_coarse])
            msg += f" | Coarse purity = {avg_coarse:.3f}"
        print(msg)

    # --- 9. Visualization ---
    print(f"\n[Step 10] Visualization...")
    _plot_scp_hierarchy(results)

    return results


def _draw_hierarchy_on_axis(ax, res, show_legend):
    """Draw one dataset's True+CFP hierarchy overlay on a single axis."""
    lvs_true = res["levels"]
    lvs_nn = res["levels_hat_nn"]
    K = res["K"]
    n_levels = len(lvs_true)

    all_c = np.vstack(lvs_true)
    pca_vis = PCA(n_components=2)
    pca_vis.fit(all_c)

    level_cmap = plt.cm.plasma
    level_colors = [level_cmap(l / max(n_levels - 1, 1))
                    for l in range(n_levels)]

    for l in range(n_levels):
        pts = pca_vis.transform(lvs_true[l])
        sz = max(80 - 10 * l, 12)
        show = show_legend and (l <= 2 or l == n_levels - 1)
        ax.scatter(
            pts[:, 0], pts[:, 1], s=sz, color=level_colors[l],
            marker="o", edgecolors="black", linewidths=0.3,
            alpha=0.85, zorder=10 - l,
            label=f"True L{l}" if show else None,
        )
        if l > 0:
            parents = pca_vis.transform(lvs_true[l - 1])
            for j in range(pts.shape[0]):
                ax.plot([parents[j // K, 0], pts[j, 0]],
                        [parents[j // K, 1], pts[j, 1]],
                        color=level_colors[l], alpha=0.3, lw=0.6, zorder=1)

    for l in range(n_levels):
        pts = pca_vis.transform(lvs_nn[l])
        sz = max(80 - 10 * l, 12)
        show = show_legend and (l <= 2 or l == n_levels - 1)
        ax.scatter(
            pts[:, 0], pts[:, 1], s=sz, color=level_colors[l],
            marker="^", edgecolors=level_colors[l], linewidths=0.8,
            facecolors="none", alpha=0.9, zorder=12 - l,
            label=f"CFP L{l}" if show else None,
        )
        if l > 0:
            parents_pred = pca_vis.transform(lvs_nn[l - 1])
            for j in range(pts.shape[0]):
                ax.plot([parents_pred[j // K, 0], pts[j, 0]],
                        [parents_pred[j // K, 1], pts[j, 1]],
                        color=level_colors[l], alpha=0.2, lw=0.5,
                        linestyle="--", zorder=0)

    ax.set_xlabel("PCA 1", fontsize=11)
    ax.set_ylabel("PCA 2", fontsize=11)
    ax.grid(True, alpha=0.15)
    ax.tick_params(labelsize=9)
    if show_legend:
        ax.legend(fontsize=7, loc="best", ncol=2,
                  handletextpad=0.3, columnspacing=0.5)


