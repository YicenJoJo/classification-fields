def _write_cifar_multiseed_summary(trial_rows, out_path):
    import csv

    metric_names = ("ordered_mse", "pi_chamfer", "dpt_distortion")
    groups = {}
    for row in trial_rows:
        key = (row["dataset"], row["level"], row["method"])
        groups.setdefault(key, {metric: [] for metric in metric_names})
        for metric in metric_names:
            groups[key][metric].append(float(row[metric]))

    summary_rows = []
    for dataset, level, method in sorted(groups):
        vals_by_metric = groups[(dataset, level, method)]
        out_row = {
            "dataset": dataset,
            "level": level,
            "method": method,
            "n_trials": len(next(iter(vals_by_metric.values()))),
        }
        for metric in metric_names:
            vals = np.array(vals_by_metric[metric], dtype=float)
            ddof = 1 if vals.size > 1 else 0
            out_row[f"{metric}_mean"] = vals.mean()
            out_row[f"{metric}_std"] = vals.std(ddof=ddof)
        summary_rows.append(out_row)

    fieldnames = [
        "dataset", "level", "method", "n_trials",
        "ordered_mse_mean", "ordered_mse_std",
        "pi_chamfer_mean", "pi_chamfer_std",
        "dpt_distortion_mean", "dpt_distortion_std",
    ]
    with open(out_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(summary_rows)

    print(f"Saved: {out_path}")
    print("\nCIFAR 5-SEED SUMMARY")
    print("=" * 120)
    for row in summary_rows:
        print(f"  {row['dataset']:<8} L={row['level']:<10} {row['method']:<18} "
              f"OrdMSE={row['ordered_mse_mean']:.6e}±{row['ordered_mse_std']:.6e}  "
              f"PI-CD={row['pi_chamfer_mean']:.6e}±{row['pi_chamfer_std']:.6e}  "
              f"d_pt={row['dpt_distortion_mean']:.6e}±{row['dpt_distortion_std']:.6e}")
    print("=" * 120)


