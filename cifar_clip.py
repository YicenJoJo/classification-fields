def get_RHG(
    C,                  # shape (d, K)
    nu=0.5,
    sigma_min=0.9,
    sigma_max=1.1,
    hidden_dim=100,
    seed=None,
):
    """
    Returns two callables:

        r_col(x): shape (d, K)
        r(x):     shape (K, d)   # transpose, for build_hierarchy(...)

    where
        A_i(x) = nu * sigmoid(B_i tanh(C_i x + c_i)) reshaped to (d,d),
        E_i(x) = expm((A_i(x)-A_i(x)^T)/2),
        Sigma(x) = diag(sigmoid(Bs tanh(Cs x + cs))*(sigma_max-sigma_min)+sigma_min),
        r_col(x) = E_1(x) Sigma(x) E_2(x) C.
    """
    rng = np.random.default_rng(seed)

    C = np.asarray(C, dtype=float)
    d, K = C.shape

    # A1 parameters
    C1 = rng.standard_normal((hidden_dim, d))
    c1 = rng.standard_normal(hidden_dim)
    B1 = rng.standard_normal((d * d, hidden_dim))

    # A2 parameters
    C2 = rng.standard_normal((hidden_dim, d))
    c2 = rng.standard_normal(hidden_dim)
    B2 = rng.standard_normal((d * d, hidden_dim))

    # Sigma parameters
    Cs = rng.standard_normal((hidden_dim, d))
    cs = rng.standard_normal(hidden_dim)
    Bs = rng.standard_normal((d, hidden_dim))

    def A_from_params(x, B, Cmat, cvec):
        h = np.tanh(Cmat @ x + cvec)               # shape (hidden_dim,)
        a = nu * sigmoid(B @ h)                    # shape (d*d,)
        return a.reshape(d, d)

    def E_from_A(A):
        Askew = 0.5 * (A - A.T)
        return expm(Askew)

    def Sigma_from_x(x):
        h = np.tanh(Cs @ x + cs)                   # shape (hidden_dim,)
        s = sigmoid(Bs @ h)                        # shape (d,)
        s = s * (sigma_max - sigma_min) + sigma_min
        return np.diag(s)

    def r_col(x):
        x = np.asarray(x, dtype=float).reshape(d)

        A1 = A_from_params(x, B1, C1, c1)
        A2 = A_from_params(x, B2, C2, c2)

        E1 = E_from_A(A1)
        E2 = E_from_A(A2)
        Sigma = Sigma_from_x(x)

        return E1 @ Sigma @ E2 @ C                # shape (d, K)

    def r(x):
        return r_col(x).T                         # shape (K, d)

    return r_col, r

